/**
 * How much of a container role a TINTED surface takes before the card surface
 * underneath it, per appearance.
 *
 * These are the only non-colour values this script emits, and they are here
 * rather than hand-written in `tokens.css` for exactly the reason the appearance
 * blocks are generated at all: anything that differs between the two schemes is
 * this script's business, and `appearance-cascade.test.ts` refuses an appearance
 * rule anywhere else.
 *
 * They cannot be one number. A container role is a pale tone (~90) in light, so
 * mixing 55% of it into a white card gives a warmed card. The SAME role in dark
 * is a saturated tone-30, and 55% of that over a near-black card is a coloured
 * slab covering the screen — which is what the first dark build of the Today
 * summary painted, and what the old overdue block painted before M3X
 * (docs/design/M3_EXPRESSIVE_AUDIT_2026_08 §4). Halving the strength in dark is
 * what makes ONE authored surface correct in both appearances.
 *
 *   expressive  the page's one branded surface (`surface-expressive`)
 *   supporting  a Level 2 supporting expressive surface (`surface-supporting`)
 *   selected    the navigation drawer's selected destination
 *   state       a record-state tint — overdue work, a flagged run
 *
 * M3X-02 added `supporting`, and it is a GENERATED pair rather than a fraction
 * of `expressive` for the same reason the other two are pairs. The intuition
 * that a supporting surface should simply take half the hero's tint is a light
 * -appearance intuition that does not survive contact with either appearance:
 * in LIGHT the page canvas is already a very pale lilac (`#f7f6fa`), so half a
 * pale container over a white card lands *between* the page and the card and
 * loses its boundary entirely — the surface stops reading as a surface. In DARK
 * the container is a saturated tone-30, and the level separation arrives long
 * before the hero's own strength does. So light sits just under the hero (the
 * level difference is carried by the wash, the elevation, the shape, the padding
 * and the text colour, all of which the hero has and this does not) and dark
 * sits well under it (where tone alone is enough).
 */
/*
 * VIS-01 adds `identity` and quietens `selected`.
 *
 * `identity` is Part 2 item A7 delivered — "calmer identity marks in dark" —
 * and it is delivered as a STRENGTH rather than as a new colour, for the reason
 * this whole block exists: an entity's container role is a pale tone-90 in
 * light and a saturated tone-30 in dark, so nine Project marks in a gallery are
 * a soft palette in one appearance and a rainbow of coloured rectangles in the
 * other. Light takes the container at full strength (nothing changes there);
 * dark takes just over half of it over the card beneath, which lands the mark
 * between the card and the accent instead of on top of both.
 *
 * It is contrast-SAFE in both directions by construction, which is why it can
 * be one mix rather than a per-ramp table: the glyph inside a mark is the
 * container's own `on-` role, and mixing a container TOWARD the card always
 * moves the background away from that role — darker under a light-on-dark
 * glyph, lighter under a dark-on-light one. Asserted over all ten ramps in
 * `contrast.test.ts`.
 *
 * `selected` is Part 2 item A2 finished. DH-DS already mixed the navigation
 * drawer's active indicator toward the drawer surface; at 62% in light it was
 * still a filled lilac capsule 216px wide, which is the single most "Material
 * component demo" object left in the frame. At 34% it is a soft wash, and the
 * three signals that were never the fill — the weight step, the `primary`
 * glyph and `aria-current` — carry exactly what they carried before.
 */
