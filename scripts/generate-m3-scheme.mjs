#!/usr/bin/env node
/**
 * M3-01 — generate the Material Design 3 colour scheme from ONE seed.
 *
 * DalyHub's colour is not authored. It is DERIVED: every role in both schemes
 * comes out of the M3 tonal-palette algorithm applied to a single source colour,
 * so "is this blue right?" is a question about the seed rather than about two
 * hundred hexes. This script is the only thing allowed to write those values.
 *
 * It emits two artefacts, both COMMITTED so neither the app nor the tests need
 * the generator at runtime:
 *
 *   1. the `:root` (light) and `@media (prefers-color-scheme: dark)` colour
 *      blocks inside `app/styles/tokens.css`, between the generated markers;
 *   2. `app/shared/tokens/scheme.ts`, the same values as typed data — the mirror
 *      the contrast and coverage tests read.
 *
 * `pnpm run scheme:check` regenerates both in memory and byte-compares them
 * against the committed files, naming the first drifted token. It runs inside
 * `pnpm run verify`, so a hand-edit to a generated colour fails the build rather
 * than surviving review (the same discipline as `icons:check`).
 *
 * Provenance: `@material/material-color-utilities` (Apache-2.0) is Google's own
 * reference implementation of the algorithm and is a DEV dependency only —
 * nothing it produces is computed at runtime, in the browser or in the Worker.
 */

