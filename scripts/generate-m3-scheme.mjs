#!/usr/bin/env node
/**
 * M3-01 / THEME-01 — generate DalyHub's Material Design 3 colour schemes.
 *
 * DalyHub's colour is not authored. It is DERIVED: every role in every scheme
 * comes out of the M3 tonal-palette algorithm applied to a small, documented set
 * of source colours, so "is this blue right?" is a question about a seed rather
 * than about two hundred hexes. This script is the only thing allowed to write
 * those values.
 *
 * ── What THEME-01 changed ────────────────────────────────────────────────────
 * M3-01 generated ONE light/dark pair from one seed. THEME-01 generates FIVE
 * light/dark pairs — one per COLOUR SCHEME — from the same machinery, the same
 * role list and the same rules. Nothing about how a colour is derived changed;
 * only how many times it is derived, and which selector each result is emitted
 * under.
 *
 * Daly Violet is byte-for-byte the scheme M3-01/M3X shipped (it still routes
 * through `SchemeVibrant`, unchanged), so the default appearance of the product
 * is untouched by this work. The other four supply their own primary, secondary,
 * tertiary and neutral palettes to the SAME `DynamicScheme` the variant builds,
 * which is what lets a scheme say "cobalt primary, violet secondary, magenta
 * tertiary" instead of accepting whatever the variant's fixed hue rotations
 * produce from one seed.
 *
 * It emits two artefacts, both COMMITTED so neither the app nor the tests need
 * the generator at runtime:
 *
 *   1. the colour blocks inside `app/styles/tokens.css`, between the generated
 *      markers — one light block and two dark blocks per scheme (see
 *      {@link buildCss} for why dark is emitted twice);
 *   2. `app/shared/tokens/scheme.ts`, the same values as typed data — the mirror
 *      the contrast and coverage tests read.
 *
 * `pnpm run scheme:check` regenerates both in memory and byte-compares them
 * against the committed files, naming the first drifted token. It runs inside
 * `pnpm run verify`, so a hand-edit to a generated colour fails the build rather
 * than surviving review (the same discipline as `icons:check`).
 *
 * Provenance: `@material/material-color-utilities` (Apache-2.0) is Google's own
 * reference implementation of the algorithm and is a DEV dependency only —
 * nothing it produces is computed at runtime, in the browser or in the Worker.
 */

