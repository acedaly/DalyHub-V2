/**
 * The surfaces the APPLICATION paints with come from their OWN generated
 * palette, not from the system container ramp.
 *
 * Why they cannot be aliases. `SchemeVibrant` is the right variant for this
 * product's PRIMARY — it keeps the seed's confidence where `SchemeTonalSpot`
 * collapses it to a muted navy — but the same variant builds its neutral palette
 * at **chroma 10**. Every rung of that ramp therefore carries a visible tint, and
 * because the application paints its page, its navigation, its filter bars and
 * its sunken panels from those rungs, the tint covers the entire product:
 *
 *     surface-container-low  #f2f3ff   chroma 9.01   ← the page canvas
 *     surface-container      #ecedfb   chroma 10.12  ← every sunken panel
 *     surface-container-high #e6e7f5   chroma 10.16  ← every raised surface
 *
 * At the near-white tones an application actually uses, chroma 9–10 at a saturated
 * hue is a wash rather than a neutral canvas. Dropping the chroma is necessary but
 * not sufficient: the Daly Violet seed's HCT hue is 295°, which sits well onto the
 * MAGENTA side of blue, so a low-chroma ramp at that hue reads as a faint lilac
 * rather than as the cool grey the design direction calls for.
 *
 * THEME-01 makes this the load-bearing half of "a scheme is a personality, not a
 * paint job" (§11): the app-neutral palette is what keeps FIVE schemes on
 * controlled neutral working surfaces, so the difference between Electric and
 * Pulse is where colour is SPENT rather than what colour the page is. Each scheme
 * therefore names its own app-neutral hue and chroma explicitly, and every one of
 * them is under chroma 6 — asserted, for all five, in `tokens.test.ts`.
 *
 * Daly Violet expresses it as a ROTATION from its seed (the M3X form, preserved
 * so the default scheme regenerates byte-identically); the four THEME-01 schemes
 * name an absolute hue, which is more legible when the seeds are five different
 * colours.
 *
 * ── Why the chroma is per APPEARANCE ─────────────────────────────────────────
 * A scheme may name one `{ hue, chroma }` or a `{ light, dark }` pair, and the
 * pair exists for the same reason `DEFAULT_TINT_STRENGTHS` is a pair: the number
 * that makes a surface right in one appearance is the wrong number in the other.
 *
 * At the near-WHITE tones a light canvas uses (92–100), chroma 8 is already a
 * visible wash — that is the PR #120 defect, and the ceiling stays where it was.
 * At the near-BLACK tones a dark canvas uses (6–26), the same chroma is a deep
 * navy that still reads unambiguously as a dark neutral: there is no white to
 * tint. Holding dark to the light ceiling is what made the first build of
 * Electric's "deep blue-black navigation" indistinguishable from Daly Violet's
 * near-black one — a scheme whose headline claim the palette could not express.
 *
 * `tokens.test.ts` asserts both ceilings separately, so the light rule is exactly
 * as strict as it was and the dark one is loose enough to be a colour scheme.
 */
