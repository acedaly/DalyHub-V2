/**
 * The M3 tone assignments for a custom colour, per scheme. These are the same
 * tones the specification gives the primary/secondary/tertiary groups, which is
 * what makes every `on-*` pair clear AA by construction rather than by luck.
 */
const CUSTOM_TONES = {
  light: { color: 40, on: 100, container: 90, onContainer: 10 },
  dark: { color: 80, on: 20, container: 30, onContainer: 90 },
};

/**
 * Resolve one custom colour to its four tones in both schemes.
 *
 * The palette is built with `TonalPalette.fromInt`, which PRESERVES the source
 * chroma. The library's own `customColor()` helper routes through
 * `CorePalette.of`, whose chroma floor of 48 turns a deliberately neutral grey
 * (`priority-p4`, `state-on-hold`, `entity-asset`) into a saturated blue —
 * indistinguishable from `priority-p3` and exactly the wrong answer for the
 * roles that mean "no colour". Recorded in ADR-074.
 */
function customTones(sourceArgb, hex) {
  const harmonised = Blend.harmonize(argbFromHex(hex), sourceArgb);
  const palette = TonalPalette.fromInt(harmonised);
  const at = (tone) => hexFromArgb(palette.tone(tone));
  return {
    light: {
      color: at(CUSTOM_TONES.light.color),
      on: at(CUSTOM_TONES.light.on),
      container: at(CUSTOM_TONES.light.container),
      onContainer: at(CUSTOM_TONES.light.onContainer),
    },
    dark: {
      color: at(CUSTOM_TONES.dark.color),
      on: at(CUSTOM_TONES.dark.on),
      container: at(CUSTOM_TONES.dark.container),
      onContainer: at(CUSTOM_TONES.dark.onContainer),
    },
  };
}

/** Build both schemes as `{ light: Record<role, hex>, dark: Record<role, hex> }`. */
function buildScheme() {
  const source = Hct.fromInt(SOURCE_COLOR);
  const schemes = {
    light: new SchemeVibrant(source, false, CONTRAST_LEVEL),
    dark: new SchemeVibrant(source, true, CONTRAST_LEVEL),
  };

  /** @type {{ light: Record<string, string>, dark: Record<string, string> }} */
  const out = { light: {}, dark: {} };
  const systemRoleNames = [];
  for (const [token, member] of Object.entries(SYSTEM_ROLES)) {
    systemRoleNames.push(token);
    for (const mode of ["light", "dark"]) {
      out[mode][token] = hexFromArgb(
        MaterialDynamicColors[member].getArgb(schemes[mode]),
      );
    }
  }

  const customGroups = [];
  for (const group of CUSTOM_COLOR_GROUPS) {
    const tokens = [];
    for (const [name, hex] of group.colors) {
      const resolved = customTones(SOURCE_COLOR, hex);
      for (const mode of ["light", "dark"]) {
        out[mode][name] = resolved[mode].color;
        out[mode][`on-${name}`] = resolved[mode].on;
        out[mode][`${name}-container`] = resolved[mode].container;
        out[mode][`on-${name}-container`] = resolved[mode].onContainer;
      }
      tokens.push(
        name,
        `on-${name}`,
        `${name}-container`,
        `on-${name}-container`,
      );
    }
    customGroups.push({ label: group.label, tokens });
  }

  // The application surfaces come out of their own generated palette (see
  // APP_SURFACE_TONES) rather than aliasing a system rung, so the CSS emits real
  // values and the TS mirror asserts contrast on exactly what the browser paints.
  const appNeutral = TonalPalette.fromHueAndChroma(
    source.hue + APP_NEUTRAL_HUE_ROTATION,
    APP_NEUTRAL_CHROMA,
  );
  const appSurfaceNames = Object.keys(APP_SURFACE_TONES.light);
  for (const mode of ["light", "dark"]) {
    for (const [name, tone] of Object.entries(APP_SURFACE_TONES[mode])) {
      out[mode][`app-${name}`] = hexFromArgb(appNeutral.tone(tone));
    }
  }

  return { scheme: out, systemRoleNames, customGroups, appSurfaceNames };
}

/** Emit the declarations for one scheme, as CSS text (no selector). */
function schemeDeclarations({ scheme, systemRoleNames, customGroups }, mode) {
  const lines = [];
  lines.push("/* System colour roles. */");
  for (const token of systemRoleNames) {
    lines.push(`--md-sys-color-${token}: ${scheme[mode][token]};`);
  }
  for (const group of customGroups) {
    lines.push("");
    lines.push(`/* ${group.label}. */`);
    for (const token of group.tokens) {
      lines.push(`--md-sys-color-${token}: ${scheme[mode][token]};`);
    }
  }
  lines.push("");
  lines.push(
    "/* Application surfaces — the generated app-neutral palette, see APP_SURFACE_TONES. */",
  );
  for (const name of Object.keys(APP_SURFACE_TONES[mode])) {
    lines.push(`--md-app-color-${name}: ${scheme[mode][`app-${name}`]};`);
  }
  lines.push("");
  lines.push(
    "/* M3X tint strengths — see APP_TINT_STRENGTHS. Numbers, not colours. */",
  );
  for (const [name, value] of Object.entries(APP_TINT_STRENGTHS[mode])) {
    lines.push(`--app-tint-strength-${name}: ${value};`);
  }
  return lines.join("\n");
}

/** Build the full generated CSS fragment (both blocks, between the markers). */
async function buildCss(built) {
  const css = [
    BEGIN_MARKER,
    "",
    "/*",
    " * Light is the base scheme. Which half of the pair actually paints is decided",
    " * by TWO inputs, in this order:",
    " *",
    " *   1. `<html data-appearance>` — the owner's stored System/Light/Dark choice",
    " *      (APPEARANCE-01), written server-side by `root.tsx` so the first byte is",
    " *      already correct: no bootstrapping script, no flash, no hydration",
    " *      mismatch;",
    " *   2. `prefers-color-scheme` — the device, which decides whenever the owner",
    " *      has chosen `system` (or has chosen nothing).",
    " *",
    " * The cascade below is what makes `system` keep UP with the device while",
    " * DalyHub is open: the media query re-evaluates itself, with no listener, no",
    " * re-render and no client state. `:not([data-appearance='light'])` is what",
    " * stops the device overriding an explicit Light, and the explicit dark block",
    " * that follows the media query is what applies an explicit Dark on a light",
    " * device. Both selectors are (0,2,0), so the later one wins on order — which",
    " * is why the explicit blocks come last.",
    " *",
    " * `color-scheme` is set alongside each, so native form controls, scrollbars",
    " * and the default canvas follow the SAME decision the tokens do. It is `light",
    " * dark` under `system` (let the browser pick) and pinned under an explicit",
    " * choice.",
    " *",
    " * There is still ONE generated light/dark pair and no palettes (ADR-074). The",
    " * only thing `data-appearance` selects is which half of that pair paints.",
    " */",
    ":root {",
    "color-scheme: light dark;",
    "",
    schemeDeclarations(built, "light"),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    ":root:not([data-appearance='light']) {",
    schemeDeclarations(built, "dark"),
    "}",
    "}",
    "",
    "/* An explicit Light: pin the native pair; the base :root already paints it. */",
    ":root[data-appearance='light'] {",
    "color-scheme: light;",
    "}",
    "",
    "/* An explicit Dark: paint dark whatever the device says. */",
    ":root[data-appearance='dark'] {",
    "color-scheme: dark;",
    "",
    schemeDeclarations(built, "dark"),
    "}",
    "",
    END_MARKER,
  ].join("\n");
  return (await prettier.format(css, { parser: "css" })).trimEnd();
}

/** Build `app/shared/tokens/scheme.ts`. */
async function buildTs(built) {
  const { scheme, systemRoleNames, customGroups, appSurfaceNames } = built;
  const roleNames = [
    ...systemRoleNames,
    ...customGroups.flatMap((group) => group.tokens),
    ...appSurfaceNames.map((name) => `app-${name}`),
  ];

  const body = `/**
 * M3-01 — the generated colour scheme, as typed data.
 *
 * @generated by scripts/generate-m3-scheme.mjs — do not hand-edit.
 *
 * The authoritative VALUES live in \`app/styles/tokens.css\`; this module is the
 * same numbers in a form TypeScript and the token tests can read. \`pnpm run
 * scheme:check\` (inside \`pnpm run verify\`) proves the two are the same bytes,
 * so a contrast test that passes here is a statement about what the browser
 * actually paints.
 *
 * Roles are the CSS token suffixes: \`primary\` is \`--md-sys-color-primary\`, and
 * \`app-surface-card\` is \`--md-app-color-surface-card\`.
 */

/** Every colour role in the scheme, in emission order. */
export const SCHEME_ROLE_NAMES = [
${roleNames.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;

/** A colour role name. */
export type SchemeRole = (typeof SCHEME_ROLE_NAMES)[number];

/** A complete colour map for one scheme. */
export type SchemeColorMap = Record<SchemeRole, string>;

/** The light scheme. */
export const LIGHT_SCHEME: SchemeColorMap = {
${roleNames.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(scheme.light[name])},`).join("\n")}
};

/** The dark scheme. */
export const DARK_SCHEME: SchemeColorMap = {
${roleNames.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(scheme.dark[name])},`).join("\n")}
};

/** Both schemes, keyed by appearance. */
export const SCHEME: { readonly light: SchemeColorMap; readonly dark: SchemeColorMap } = {
  light: LIGHT_SCHEME,
  dark: DARK_SCHEME,
};

/** The seed every value above is derived from. */
export const SOURCE_COLOR = ${JSON.stringify(SEED_HEX)};
`;
  return prettier.format(body, { parser: "typescript" });
}

/** Splice the generated CSS between the markers in `tokens.css`. */
function spliceCss(existing, fragment) {
  const begin = existing.indexOf(BEGIN_MARKER);
  const end = existing.indexOf(END_MARKER);
  if (begin === -1 || end === -1) {
    throw new Error(
      `tokens.css is missing the generated markers; expected ${BEGIN_MARKER} … ${END_MARKER}`,
    );
  }
  return (
    existing.slice(0, begin) +
    fragment +
    existing.slice(end + END_MARKER.length)
  );
}

/** Report the first drifted line as a token name, not as a diff hunk. */
function describeDrift(expected, actual, label) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const max = Math.max(expectedLines.length, actualLines.length);
  for (let i = 0; i < max; i += 1) {
    if (expectedLines[i] === actualLines[i]) continue;
    const token = /(--[\w-]+|"[\w-]+")/.exec(actualLines[i] ?? "")?.[1];
    return [
      `${label} has drifted from the generator at line ${i + 1}${token ? ` (${token})` : ""}:`,
      `  committed: ${actualLines[i] ?? "<end of file>"}`,
      `  generated: ${expectedLines[i] ?? "<end of file>"}`,
    ].join("\n");
  }
  return `${label} has drifted from the generator.`;
}

async function main() {
  const check = process.argv.includes("--check");
  const built = buildScheme();
  const cssFragment = await buildCss(built);
  const ts = await buildTs(built);

  const existingCss = readFileSync(TOKENS_CSS, "utf8");
  const nextCss = spliceCss(existingCss, cssFragment);

  if (check) {
    const problems = [];
    if (nextCss !== existingCss) {
      problems.push(
        describeDrift(nextCss, existingCss, "app/styles/tokens.css"),
      );
    }
    const existingTs = readFileSync(SCHEME_TS, "utf8");
    if (existingTs !== ts) {
      problems.push(
        describeDrift(ts, existingTs, "app/shared/tokens/scheme.ts"),
      );
    }
    if (problems.length > 0) {
      console.error(problems.join("\n\n"));
      console.error("\nRun `pnpm run scheme:generate` to regenerate.");
      process.exitCode = 1;
      return;
    }
    console.log("scheme:check — tokens.css and scheme.ts match the generator.");
    return;
  }

  writeFileSync(TOKENS_CSS, nextCss);
  writeFileSync(SCHEME_TS, ts);
  const roleCount = Object.keys(built.scheme.light).length;
  console.log(
    `scheme:generate — wrote ${roleCount} roles per scheme to tokens.css and scheme.ts.`,
  );
}

await main();
