/**
 * The `DynamicScheme` for one scheme in one appearance.
 *
 * Daly Violet takes the variant's own constructor so its output is provably the
 * scheme M3X shipped. The others hand the SAME variant explicit palettes, which
 * the library supports directly — `DynamicScheme` derives a palette from the
 * variant only when the caller does not supply one, and every role above is then
 * computed by identical code. A unit-level equivalence check is not needed here
 * because `scheme:check` compares the whole emitted artefact.
 */
function dynamicScheme(scheme, isDark) {
  const sourceColorHct = Hct.fromInt(argbFromHex(scheme.seed));
  if (scheme.palettes === "vibrant") {
    return new SchemeVibrant(sourceColorHct, isDark, CONTRAST_LEVEL);
  }
  return new DynamicScheme({
    sourceColorHct,
    variant: Variant.VIBRANT,
    contrastLevel: CONTRAST_LEVEL,
    isDark,
    primaryPalette: scheme.palettes.primary,
    secondaryPalette: scheme.palettes.secondary,
    tertiaryPalette: scheme.palettes.tertiary,
    neutralPalette: scheme.palettes.neutral,
    neutralVariantPalette: scheme.palettes.neutralVariant,
  });
}

/** Build one scheme as `{ light: Record<role, hex>, dark: Record<role, hex> }`. */
function buildOneScheme(scheme) {
  const sourceArgb = argbFromHex(scheme.seed);
  const sourceHct = Hct.fromInt(sourceArgb);
  const schemes = {
    light: dynamicScheme(scheme, false),
    dark: dynamicScheme(scheme, true),
  };

  /** @type {{ light: Record<string, string>, dark: Record<string, string> }} */
  const out = { light: {}, dark: {} };
  const systemRoleNames = [];
  for (const [token, member] of Object.entries(SYSTEM_ROLES)) {
    systemRoleNames.push(token);
    for (const mode of ["light", "dark"]) {
      out[mode][token] = hexFromArgb(
        MaterialDynamicColors[member].getArgb(schemes[mode]),
      );
    }
  }

  const customGroups = [];
  for (const group of customColorGroups(scheme)) {
    const tokens = [];
    for (const [name, hex] of group.colors) {
      const resolved = customTones(sourceArgb, hex);
      for (const mode of ["light", "dark"]) {
        out[mode][name] = resolved[mode].color;
        out[mode][`on-${name}`] = resolved[mode].on;
        out[mode][`${name}-container`] = resolved[mode].container;
        out[mode][`on-${name}-container`] = resolved[mode].onContainer;
      }
      tokens.push(
        name,
        `on-${name}`,
        `${name}-container`,
        `on-${name}-container`,
      );
    }
    customGroups.push({ label: group.label, tokens });
  }

  // The application surfaces come out of their own generated palette (see
  // DEFAULT_SURFACE_TONES) rather than aliasing a system rung, so the CSS emits
  // real values and the TS mirror asserts contrast on exactly what the browser
  // paints.
  const tones = surfaceTones(scheme);
  const appSurfaceNames = Object.keys(tones.light);
  for (const mode of ["light", "dark"]) {
    const spec = scheme.appNeutral[mode] ?? scheme.appNeutral;
    const appNeutral = TonalPalette.fromHueAndChroma(
      spec.hue ?? sourceHct.hue + spec.rotation,
      spec.chroma,
    );
    for (const [name, tone] of Object.entries(tones[mode])) {
      out[mode][`app-${name}`] = hexFromArgb(appNeutral.tone(tone));
    }
  }

  /*
   * The rail's ACCENT SOURCE, which is a different role per appearance.
   *
   * The current destination is the product's colour mixed into the rail, and
   * which ROLE supplies that colour cannot be the same in both appearances — the
   * reason is M3's own construction rather than a DalyHub preference. `primary`
   * is a saturated mid-tone violet in LIGHT and a pale tone-80 violet in DARK,
   * because in dark it has to be legible AS TEXT on a dark surface. Mixing the
   * dark-appearance `primary` into a near-black rail produces a pale lavender
   * pill — a light object on a dark rail, the opposite of the block that
   * appearance needs, and measured on the first build of DS-03.
   *
   * `primary-container` is the mirror image: a pale lilac in light and a
   * saturated tone-30 violet in dark, because a CONTAINER is a surface rather
   * than a foreground. So each appearance takes the role that is the saturated
   * violet IN that appearance, and the one `color-mix` in `tokens.css` is then
   * correct in both without an appearance rule anywhere outside this file —
   * which is what `appearance-cascade.test.ts` requires.
   *
   * FINAL-UI keeps both assignments and they now mean something slightly
   * different in light: `primary` at 12% is the pale lavender ROW rather than a
   * block, and the saturated source is what keeps that tint the product's violet
   * rather than a grey with a hint of blue.
   *
   * It is emitted alongside the application surfaces because that is what it is:
   * a value the APPLICATION composes a surface from. It is deliberately not an
   * entry in the surface-tone table — it does not come from the app-neutral
   * palette at all, which is the whole point of it.
   */
  out.light["app-rail-accent"] = out.light.primary;
  out.dark["app-rail-accent"] = out.dark["primary-container"];
  appSurfaceNames.push("rail-accent");

  /*
   * FINAL-UI — the SELECTED destination's foreground, resolved per appearance.
   *
   * A light rail's current row is a pale tint, and the thing that makes it read
   * as chosen rather than as a smudge is that its label and glyph turn the
   * product's violet (concept 3 draws precisely this). A dark rail's current row
   * is a saturated block, and violet-on-violet is the least legible pairing on
   * the whole frame — there the foreground is the rail's own light text.
   *
   * Same token, opposite roles, no appearance rule in `shell.css`. Both pairs
   * are asserted against the mixed selected surface in `contrast.test.ts`.
   */
  out.light["app-on-rail-selected"] = out.light.primary;
  out.dark["app-on-rail-selected"] = out.dark["app-on-rail"];
  appSurfaceNames.push("on-rail-selected");

  return { colors: out, systemRoleNames, customGroups, appSurfaceNames };
}

/**
 * Build every scheme, plus the shared role-name list.
 *
 * The role names are asserted to be identical across schemes: a scheme that
 * defined a role its neighbours did not would fall through to whatever the
 * previous block left behind, which is precisely the "Electric quietly has no
 * `primary-container`" failure THEME-01 §41 rules out. Here it is impossible
 * rather than tested-for, because the list is built once and reused.
 */
function buildAll() {
  const built = COLOR_SCHEMES.map((scheme) => ({
    scheme,
    ...buildOneScheme(scheme),
  }));
  const reference = built[0];
  const roleNames = [
    ...reference.systemRoleNames,
    ...reference.customGroups.flatMap((group) => group.tokens),
    ...reference.appSurfaceNames.map((name) => `app-${name}`),
  ];
  for (const entry of built) {
    const missing = roleNames.filter(
      (role) =>
        entry.colors.light[role] === undefined ||
        entry.colors.dark[role] === undefined,
    );
    if (missing.length > 0) {
      throw new Error(
        `scheme "${entry.scheme.key}" is missing roles: ${missing.join(", ")}`,
      );
    }
  }
  return { built, roleNames, reference };
}

/**
 * The preview declarations — every scheme's three swatch colours, in one
 * appearance. Identical in every block of that appearance, which is what makes
 * the Settings picker show five honest previews whichever scheme is active.
 */
function previewDeclarations(all, mode) {
  const lines = ["", "/* THEME-01 scheme previews — see PREVIEW_SLOTS. */"];
  for (const entry of all.built) {
    for (const slot of PREVIEW_SLOTS) {
      lines.push(
        `--md-app-color-preview-${entry.scheme.key}-${slot}: ${entry.colors[mode][slot]};`,
      );
    }
  }
  return lines;
}

/** Emit the declarations for one scheme in one appearance, as CSS text. */
function schemeDeclarations(all, entry, mode) {
  const lines = [];
  lines.push("/* System colour roles. */");
  for (const token of entry.systemRoleNames) {
    lines.push(`--md-sys-color-${token}: ${entry.colors[mode][token]};`);
  }
  for (const group of entry.customGroups) {
    lines.push("");
    lines.push(`/* ${group.label}. */`);
    for (const token of group.tokens) {
      lines.push(`--md-sys-color-${token}: ${entry.colors[mode][token]};`);
    }
  }
  lines.push("");
  lines.push(
    "/* Application surfaces — the generated app-neutral palette, see DEFAULT_SURFACE_TONES. */",
  );
  for (const name of entry.appSurfaceNames) {
    lines.push(`--md-app-color-${name}: ${entry.colors[mode][`app-${name}`]};`);
  }
  lines.push("");
  lines.push(
    "/* M3X tint strengths — see DEFAULT_TINT_STRENGTHS. Numbers, not colours. */",
  );
  for (const [name, value] of Object.entries(
    tintStrengths(entry.scheme)[mode],
  )) {
    lines.push(`--app-tint-strength-${name}: ${value};`);
  }
  lines.push(...previewDeclarations(all, mode));
  return lines.join("\n");
}

/**
 * The selector a scheme's LIGHT block takes.
 *
 * The default scheme has none: it is the bare `:root`, so a document that never
 * got an attribute — a root error boundary, a stylesheet loaded by a test — is
 * still fully painted in Daly Violet rather than left unstyled (THEME-01 §30).
 */
function lightSelector(key) {
  return key === DEFAULT_COLOR_SCHEME
    ? ":root"
    : `:root[data-color-scheme="${key}"]`;
}

/**
 * The selectors a scheme's DARK block takes, given the appearance condition.
 *
 * `condition` is `:not([data-appearance="light"])` inside the device media query
 * and `[data-appearance="dark"]` for the explicit block. The default scheme
 * matches BOTH its own attribute and the absence of one, which is why it emits a
 * selector list.
 *
 * Every selector here carries two attribute clauses, so it is (0,3,0) and beats
 * the (0,2,0) light block of any scheme regardless of source order. That is the
 * whole cascade: light blocks establish a scheme, dark blocks override it, and no
 * pair of them can ever tie.
 */
function darkSelectors(key, condition) {
  if (key === DEFAULT_COLOR_SCHEME) {
    return [
      `:root:not([data-color-scheme])${condition}`,
      `:root[data-color-scheme="${key}"]${condition}`,
    ];
  }
  return [`:root[data-color-scheme="${key}"]${condition}`];
}

/** Build the full generated CSS fragment (every block, between the markers). */
async function buildCss(all) {
  const { built } = all;
  const byKey = (key) => built.find((entry) => entry.scheme.key === key);
  const css = [
    BEGIN_MARKER,
    "",
    "/*",
    " * TWO independent inputs decide what this stylesheet paints, and they are",
    " * deliberately orthogonal (THEME-01 §3):",
    " *",
    " *   `<html data-color-scheme>`  WHICH SCHEME — Daly Violet, Electric, Pulse,",
    " *                               Ocean or Graphite. Colour personality only:",
    " *                               no layout, type, shape or motion token is",
    " *                               scheme-dependent, here or anywhere.",
    " *   `<html data-appearance>`    WHICH HALF of that scheme's pair — the",
    " *                               owner's stored System/Light/Dark choice",
    " *                               (APPEARANCE-01).",
    " *",
    " * Both are written server-side by `root.tsx`, so the first byte is already",
    " * correct: no bootstrapping script, no flash, no hydration mismatch.",
    " *",
    " * The cascade, in the order it is emitted below:",
    " *",
    " *   1. `:root` — Daly Violet, light. The base, and the FALLBACK: a document",
    " *      with no attribute at all is fully painted in the default scheme.",
    " *   2. `:root[data-color-scheme=…]` — each other scheme's light block,",
    " *      (0,2,0), beating the base.",
    " *   3. the `prefers-color-scheme: dark` media block — each scheme's dark",
    " *      values, guarded by `:not([data-appearance='light'])` so a dark device",
    " *      cannot override an explicit Light. Every selector is (0,3,0), so it",
    " *      beats every light block whatever the order.",
    " *   4. an explicit Light, which needs no colours (the light blocks already",
    " *      paint) and only pins `color-scheme`.",
    " *   5. an explicit Dark per scheme, (0,3,0), emitted last so it also wins on",
    " *      order against the identical media-query rule on a dark device.",
    " *",
    " * `color-scheme` is set alongside each, so native form controls, scrollbars",
    " * and the default canvas follow the SAME decision the tokens do. It is `light",
    " * dark` under `system` (let the browser pick) and pinned under an explicit",
    " * choice.",
    " *",
    " * A stale or unknown `data-color-scheme` value matches no block and lands on",
    " * the base `:root` — Daly Violet — which is the required safe fallback (§30)",
    " * expressed as a property of the cascade rather than as a runtime check.",
    " */",
    `${lightSelector(DEFAULT_COLOR_SCHEME)} {`,
    "color-scheme: light dark;",
    "",
    schemeDeclarations(all, byKey(DEFAULT_COLOR_SCHEME), "light"),
    "}",
  ];

  for (const entry of built) {
    if (entry.scheme.key === DEFAULT_COLOR_SCHEME) continue;
    css.push(
      "",
      `/* ${entry.scheme.label} — light. */`,
      `${lightSelector(entry.scheme.key)} {`,
      schemeDeclarations(all, entry, "light"),
      "}",
    );
  }

  css.push("", "@media (prefers-color-scheme: dark) {");
  for (const entry of built) {
    css.push(
      `/* ${entry.scheme.label} — the device's dark. */`,
      `${darkSelectors(entry.scheme.key, ':not([data-appearance="light"])').join(",\n")} {`,
      schemeDeclarations(all, entry, "dark"),
      "}",
      "",
    );
  }
  css.push("}");

  css.push(
    "",
    "/* An explicit Light: pin the native pair; the light blocks already paint it. */",
    ':root[data-appearance="light"] {',
    "color-scheme: light;",
    "}",
  );

  for (const entry of built) {
    css.push(
      "",
      `/* ${entry.scheme.label} — an explicit Dark, whatever the device says. */`,
      `${darkSelectors(entry.scheme.key, '[data-appearance="dark"]').join(",\n")} {`,
      "color-scheme: dark;",
      "",
      schemeDeclarations(all, entry, "dark"),
      "}",
    );
  }

  css.push("", END_MARKER);
  return (await prettier.format(css.join("\n"), { parser: "css" })).trimEnd();
}

/** Build `app/shared/tokens/scheme.ts`. */
async function buildTs(all) {
  const { built, roleNames } = all;
  const literal = (colors) =>
    roleNames
      .map(
        (name) => `  ${JSON.stringify(name)}: ${JSON.stringify(colors[name])},`,
      )
      .join("\n");

  const body = `/**
 * M3-01 / THEME-01 — the generated colour schemes, as typed data.
 *
 * @generated by scripts/generate-m3-scheme.mjs — do not hand-edit.
 *
 * The authoritative VALUES live in \`app/styles/tokens.css\`; this module is the
 * same numbers in a form TypeScript and the token tests can read. \`pnpm run
 * scheme:check\` (inside \`pnpm run verify\`) proves the two are the same bytes,
 * so a contrast test that passes here is a statement about what the browser
 * actually paints.
 *
 * Roles are the CSS token suffixes: \`primary\` is \`--md-sys-color-primary\`, and
 * \`app-surface-card\` is \`--md-app-color-surface-card\`.
 *
 * Every scheme defines every role in both appearances — the generator refuses to
 * emit otherwise — so \`COLOR_SCHEME_PALETTES[scheme][appearance][role]\` is total.
 */

/** Every colour role in a scheme, in emission order. */
export const SCHEME_ROLE_NAMES = [
${roleNames.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;

/** A colour role name. */
export type SchemeRole = (typeof SCHEME_ROLE_NAMES)[number];

/** A complete colour map for one scheme in one appearance. */
export type SchemeColorMap = Record<SchemeRole, string>;

/** Both appearances of one colour scheme. */
export type SchemeColorPair = {
  readonly light: SchemeColorMap;
  readonly dark: SchemeColorMap;
};

/** The generated colour-scheme keys, in presentation order. */
export const GENERATED_COLOR_SCHEMES = [
${built.map((entry) => `  ${JSON.stringify(entry.scheme.key)},`).join("\n")}
] as const;

/** A generated colour-scheme key. */
export type GeneratedColorScheme = (typeof GENERATED_COLOR_SCHEMES)[number];

/** The seed each scheme is derived from, for documentation and tests. */
export const COLOR_SCHEME_SEEDS: Record<GeneratedColorScheme, string> = {
${built.map((entry) => `  ${JSON.stringify(entry.scheme.key)}: ${JSON.stringify(entry.scheme.seed)},`).join("\n")}
};

/** The composed-surface tint strengths, as PERCENTAGES, per scheme and appearance.
 *
 * The stylesheet carries the same numbers as \`--app-tint-strength-*\`. They are
 * mirrored here because the surfaces they compose — the expressive hero, a washed
 * glance widget, the selected navigation row — are \`color-mix()\` results rather
 * than roles, so the contrast tests have to reproduce the mix, and a scheme may
 * override any of them (Pulse does). */
export const COLOR_SCHEME_TINT_STRENGTHS: Record<
  GeneratedColorScheme,
  { readonly light: Record<string, number>; readonly dark: Record<string, number> }
> = {
${built
  .map(
    (entry) =>
      `  ${entry.scheme.key}: { light: ${JSON.stringify(percentages(tintStrengths(entry.scheme).light))}, dark: ${JSON.stringify(percentages(tintStrengths(entry.scheme).dark))} },`,
  )
  .join("\n")}
};

${built
  .map(
    (entry) => `/** ${entry.scheme.label} — light. */
const ${entry.scheme.key.toUpperCase()}_LIGHT: SchemeColorMap = {
${literal(entry.colors.light)}
};

/** ${entry.scheme.label} — dark. */
const ${entry.scheme.key.toUpperCase()}_DARK: SchemeColorMap = {
${literal(entry.colors.dark)}
};`,
  )
  .join("\n\n")}

/** Every scheme, keyed by scheme then appearance. */
export const COLOR_SCHEME_PALETTES: Record<
  GeneratedColorScheme,
  SchemeColorPair
> = {
${built
  .map(
    (entry) =>
      `  ${entry.scheme.key}: { light: ${entry.scheme.key.toUpperCase()}_LIGHT, dark: ${entry.scheme.key.toUpperCase()}_DARK },`,
  )
  .join("\n")}
};

/** The DEFAULT scheme's light map — what a document with no attribute paints. */
export const LIGHT_SCHEME: SchemeColorMap = ${DEFAULT_COLOR_SCHEME.toUpperCase()}_LIGHT;

/** The DEFAULT scheme's dark map. */
export const DARK_SCHEME: SchemeColorMap = ${DEFAULT_COLOR_SCHEME.toUpperCase()}_DARK;

/** The default scheme, both appearances, keyed by appearance. */
export const SCHEME: SchemeColorPair = COLOR_SCHEME_PALETTES.${DEFAULT_COLOR_SCHEME};

/** The seed the default scheme is derived from. */
export const SOURCE_COLOR = ${JSON.stringify(byDefaultSeed(built))};
`;
  return prettier.format(body, { parser: "typescript" });
}

/** `{ expressive: "55%" }` → `{ expressive: 55 }`, for the TS mirror. */
function percentages(table) {
  return Object.fromEntries(
    Object.entries(table).map(([name, value]) => [
      name,
      Number.parseInt(value, 10),
    ]),
  );
}

/** The default scheme's seed, as written into the TS mirror. */
function byDefaultSeed(built) {
  return built.find((entry) => entry.scheme.key === DEFAULT_COLOR_SCHEME).scheme
    .seed;
}

/** Splice the generated CSS between the markers in `tokens.css`. */
function spliceCss(existing, fragment) {
  const begin = existing.indexOf(BEGIN_MARKER);
  const end = existing.indexOf(END_MARKER);
  if (begin === -1 || end === -1) {
    throw new Error(
      `tokens.css is missing the generated markers; expected ${BEGIN_MARKER} … ${END_MARKER}`,
    );
  }
  return (
    existing.slice(0, begin) +
    fragment +
    existing.slice(end + END_MARKER.length)
  );
}

/** Report the first drifted line as a token name, not as a diff hunk. */
function describeDrift(expected, actual, label) {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const max = Math.max(expectedLines.length, actualLines.length);
  for (let i = 0; i < max; i += 1) {
    if (expectedLines[i] === actualLines[i]) continue;
    const token = /(--[\w-]+|"[\w-]+")/.exec(actualLines[i] ?? "")?.[1];
    return [
      `${label} has drifted from the generator at line ${i + 1}${token ? ` (${token})` : ""}:`,
      `  committed: ${actualLines[i] ?? "<end of file>"}`,
      `  generated: ${expectedLines[i] ?? "<end of file>"}`,
    ].join("\n");
  }
  return `${label} has drifted from the generator.`;
}

async function main() {
  const check = process.argv.includes("--check");
  const all = buildAll();
  const cssFragment = await buildCss(all);
  const ts = await buildTs(all);

  const existingCss = readFileSync(TOKENS_CSS, "utf8");
  const nextCss = spliceCss(existingCss, cssFragment);

  if (check) {
    const problems = [];
    if (nextCss !== existingCss) {
      problems.push(
        describeDrift(nextCss, existingCss, "app/styles/tokens.css"),
      );
    }
    const existingTs = readFileSync(SCHEME_TS, "utf8");
    if (existingTs !== ts) {
      problems.push(
        describeDrift(ts, existingTs, "app/shared/tokens/scheme.ts"),
      );
    }
    if (problems.length > 0) {
      console.error(problems.join("\n\n"));
      console.error("\nRun `pnpm run scheme:generate` to regenerate.");
      process.exitCode = 1;
      return;
    }
    console.log("scheme:check — tokens.css and scheme.ts match the generator.");
    return;
  }

  writeFileSync(TOKENS_CSS, nextCss);
  writeFileSync(SCHEME_TS, ts);
  console.log(
    `scheme:generate — wrote ${all.roleNames.length} roles × ${all.built.length} schemes × 2 appearances to tokens.css and scheme.ts.`,
  );
}

await main();
